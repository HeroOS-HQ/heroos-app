"""Client-side PostgreSQL SCRAM-SHA-256 password verifiers and password policy.

``ALTER ROLE ... PASSWORD 'SCRAM-SHA-256$...'`` stores a pre-computed verifier
as is, so the plaintext password never travels in SQL text. A statement that
fails is logged by the server (``log_min_error_statement``), and psql echoes
failing statements: neither can then reveal the password.

Verifier format (PostgreSQL ``scram_build_secret``, RFC 5803)::

    SCRAM-SHA-256$<iterations>:<base64 salt>$<base64 StoredKey>:<base64 ServerKey>

PostgreSQL applies SASLprep to the password first. The managed passwords are
lowercase hex, for which SASLprep is the identity; anything else is refused.
"""

import base64
import hashlib
import hmac
import re
import secrets
from typing import Final

ITERATIONS: Final = 4096  # PostgreSQL default scram_iterations
SALT_BYTES: Final = 16  # PostgreSQL SCRAM_DEFAULT_SALT_LEN

# Every managed database password is 32 random bytes as lowercase hex: URL-,
# shell- and dotenv-safe without quoting or escaping. Placeholders, the retired
# committed development defaults and hand-typed passwords never match.
PASSWORD_PATTERN: Final = re.compile(r"[0-9a-f]{64}")


class PasswordPolicyError(ValueError):
    """A password does not meet the managed-password policy. Never quotes it."""


def generate_password() -> str:
    return secrets.token_hex(32)


def check_password(password: str | None, name: str) -> str:
    if not password or not PASSWORD_PATTERN.fullmatch(password):
        raise PasswordPolicyError(
            f"{name} must be 64 lowercase hex characters generated by "
            "`make env-init` / `make env-rotate`"
        )
    return password


def _hmac(key: bytes, message: bytes) -> bytes:
    return hmac.new(key, message, hashlib.sha256).digest()


def scram_keys(password: str, salt: bytes, iterations: int = ITERATIONS) -> tuple[bytes, bytes]:
    """Return (StoredKey, ServerKey) for ``password``."""
    if not password.isascii() or not password.isprintable():
        # SASLprep is the identity only for printable ASCII.
        raise PasswordPolicyError("password must be printable ASCII")
    salted = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, iterations)
    stored_key = hashlib.sha256(_hmac(salted, b"Client Key")).digest()
    server_key = _hmac(salted, b"Server Key")
    return stored_key, server_key


def scram_verifier(
    password: str, *, salt: bytes | None = None, iterations: int = ITERATIONS
) -> str:
    salt = secrets.token_bytes(SALT_BYTES) if salt is None else salt
    stored_key, server_key = scram_keys(password, salt, iterations)

    def b64(value: bytes) -> str:
        return base64.b64encode(value).decode()

    return f"SCRAM-SHA-256${iterations}:{b64(salt)}${b64(stored_key)}:{b64(server_key)}"


def redact_verifiers(text: str) -> str:
    return re.sub(r"SCRAM-SHA-256\$\S+", "SCRAM-SHA-256$<redacted>", text)
