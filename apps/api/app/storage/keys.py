"""Canonical, server-generated storage keys.

A storage key is derived only from two UUIDs that HeroOS controls:

    companies/<company uuid>/<object uuid>

- The Company UUID comes from trusted ``CompanyScope`` (Membership-derived),
  never from a request body, query, header, filename or the key itself.
- The object UUID is generated by HeroOS (``uuid4``) when an object is stored.
  Clients may later present it as an identifier, but it is parsed as a UUID and
  re-rendered canonically; it never becomes a path fragment as supplied.
- Original filenames, if ever supported, are metadata only and never part of a
  key.

``StorageKey`` cannot be built from an arbitrary string except through
``StorageKey.parse``, which accepts only the exact canonical form.
"""

import re
from dataclasses import dataclass
from uuid import UUID

from app.storage.errors import InvalidStorageKeyError

KEY_PREFIX = "companies"

_CANONICAL_UUID = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
_CANONICAL_UUID_PATTERN = re.compile(_CANONICAL_UUID)
_CANONICAL_KEY_PATTERN = re.compile(
    rf"{KEY_PREFIX}/(?P<company>{_CANONICAL_UUID})/(?P<object>{_CANONICAL_UUID})"
)


def _require_uuid(value: object) -> UUID:
    # Only real, non-nil UUID instances reach key construction.
    if not isinstance(value, UUID) or value.int == 0:
        raise InvalidStorageKeyError("storage keys require non-nil UUIDs")
    return value


def parse_object_id(value: str) -> UUID:
    """Parse a client-presented object identifier.

    Accepts only the canonical lowercase hyphenated UUID form. Paths, encoded
    separators, braces, ``urn:uuid:`` prefixes and anything else are rejected
    before they can reach a storage provider.
    """
    if not isinstance(value, str) or not _CANONICAL_UUID_PATTERN.fullmatch(value):
        raise InvalidStorageKeyError("object identifier is not a canonical UUID")
    return _require_uuid(UUID(value))


@dataclass(frozen=True, slots=True)
class StorageKey:
    """A validated canonical key: one object inside one Company namespace."""

    company_id: UUID
    object_id: UUID

    def __post_init__(self) -> None:
        _require_uuid(self.company_id)
        _require_uuid(self.object_id)

    @classmethod
    def for_object(cls, company_id: UUID, object_id: UUID) -> "StorageKey":
        return cls(company_id=company_id, object_id=object_id)

    @classmethod
    def parse(cls, value: str) -> "StorageKey":
        """Parse a canonical key string, rejecting every other form."""
        match = _CANONICAL_KEY_PATTERN.fullmatch(value) if isinstance(value, str) else None
        if match is None:
            raise InvalidStorageKeyError("not a canonical storage key")
        return cls(company_id=UUID(match["company"]), object_id=UUID(match["object"]))

    @property
    def parts(self) -> tuple[str, str, str]:
        """Path segments; each is a fixed prefix or a canonical UUID string."""
        return (KEY_PREFIX, str(self.company_id), str(self.object_id))

    def __str__(self) -> str:
        return "/".join(self.parts)
